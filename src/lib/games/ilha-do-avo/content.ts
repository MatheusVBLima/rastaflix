/** Curva de XP necessária por nível (ritmo estilo Vampire Survivors). */
export function xpRequiredForLevel(level: number): number {
  return Math.round(7 + (level - 1) * 6 + Math.pow(Math.max(0, level - 1), 1.36) * 2.0);
}
